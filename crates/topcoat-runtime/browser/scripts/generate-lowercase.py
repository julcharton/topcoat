#!/usr/bin/env python3
"""Generate browser lowercase tables from checksummed Unicode data."""

import hashlib
from pathlib import Path
from urllib.request import urlopen

SOURCES = {
    "17.0.0": {
        "UnicodeData.txt": "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
        "SpecialCasing.txt": "efc25faf19de21b92c1194c111c932e03d2a5eaf18194e33f1156e96de4c9588",
        "DerivedCoreProperties.txt": "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08",
    },
    "18.0.0": {
        "UnicodeData.txt": "0736451de439ae7baf1425136617da495e09ee5afbe6e394374db7009ea08950",
        "SpecialCasing.txt": "8538dea57c184f1ef3783885ea79677b10f6efa06423717157e63712f14d1ad2",
        "DerivedCoreProperties.txt": "09c928886a178fcafd93c29e4bd59073a058e5a100b716d425cb563ab50f68c9",
    },
}
ROOT = Path(__file__).resolve().parent.parent


def records(version, name):
    with urlopen(f"https://www.unicode.org/Public/{version}/ucd/{name}", timeout=30) as response:
        data = response.read()
    if hashlib.sha256(data).hexdigest() != SOURCES[version][name]:
        raise ValueError(f"Unicode source checksum mismatch: {name}")
    for line in data.decode("utf-8").splitlines():
        body = line.split("#", 1)[0].strip()
        if body:
            yield [field.strip() for field in body.split(";")]


def escape(code):
    return rf"\u{{{code:x}}}"


def property_pattern(ranges):
    # Merge adjacent ranges, which the UCD separates by general category.
    merged = []
    for start, end in sorted(ranges):
        if merged and start == merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], end)
        else:
            merged.append((start, end))
    return "/[" + "".join(
        escape(start) if start == end else f"{escape(start)}-{escape(end)}"
        for start, end in merged
    ) + "]/u"


def tables(version):
    mappings = {}
    for row in records(version, "UnicodeData.txt"):
        if row[13]:
            mappings[int(row[0], 16)] = [int(row[13], 16)]
    for row in records(version, "SpecialCasing.txt"):
        code = int(row[0], 16)
        if not row[4]:
            mappings[code] = [int(part, 16) for part in row[1].split()]
        elif not any(language in row[4].split() for language in ("tr", "az", "lt")):
            # The runtime handles the only locale-independent contextual rule.
            if (code, row[1], row[4]) != (0x3A3, "03C2", "Final_Sigma"):
                raise ValueError(f"Unhandled lowercase context: {row}")

    simple = sorted(
        (code, lower[0] - code)
        for code, lower in mappings.items()
        if len(lower) == 1 and lower[0] != code
    )
    ranges = []
    index = 0
    while index < len(simple):
        start, delta = simple[index]
        end, step = start, 1
        if index + 1 < len(simple):
            next_code, next_delta = simple[index + 1]
            if next_delta == delta and next_code - start in (1, 2):
                step = next_code - start
                while index + 1 < len(simple) and simple[index + 1] == (end + step, delta):
                    index += 1
                    end += step
        ranges.append((start, end, step, delta))
        index += 1

    properties = {"Cased": [], "Case_Ignorable": []}
    for row in records(version, "DerivedCoreProperties.txt"):
        if row[1] in properties:
            bounds = [int(part, 16) for part in row[0].split("..")]
            properties[row[1]].append((bounds[0], bounds[-1]))

    output = [
        f'"{version}": {{',
        "ranges: [",
    ]
    output.extend(
        f"\t[0x{start:x}, 0x{end:x}, {step}, {delta}],"
        for start, end, step, delta in ranges
    )
    output.extend([
        "],", "expansions: {",
    ])
    output.extend(
        f'\t0x{code:x}: "{"".join(escape(part) for part in lower)}",'
        for code, lower in sorted(mappings.items()) if len(lower) > 1
    )
    output.extend([
        "},",
        f'cased: {property_pattern(properties["Cased"])},',
        f'caseIgnorable: {property_pattern(properties["Case_Ignorable"])},', "},",
    ])
    return output


def main():
    license_text = (ROOT / "scripts/UNICODE-LICENSE.txt").read_text()
    output = [
        f"/*!\n{license_text.rstrip()}\n*/",
        "// Generated by scripts/generate-lowercase.py. Do not edit.",
        "// biome-ignore-all lint/suspicious/noMisleadingCharacterClass: Generated Unicode properties match individual scalars, not grapheme clusters.",
        "// Sources: UnicodeData, SpecialCasing, DerivedCoreProperties.",
        "export type LowercaseRange = readonly [start: number, end: number, step: number, delta: number];",
        "export type LowercaseTables = {",
        "ranges: readonly LowercaseRange[];",
        "expansions: Readonly<Record<number, string>>;",
        "cased: RegExp;",
        "caseIgnorable: RegExp;",
        "};", "",
        "export const LOWERCASE_TABLES: Readonly<Record<string, LowercaseTables>> = {",
    ]
    for version in SOURCES:
        output.extend(tables(version))
    output.extend(["};", ""])
    (ROOT / "src/surrogate/string/lowercase-data.ts").write_text("\n".join(output), encoding="ascii")


if __name__ == "__main__":
    main()
